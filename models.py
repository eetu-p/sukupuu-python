class Person:
    def __init__(
            self, 
            id, 
            given_name, 
            last_name, 
            date_of_birth, 
            date_of_death
            ):
        self.id = id
        self.given_name = given_name
        self.last_name = last_name
        self.date_of_birth = date_of_birth
        self.date_of_death = date_of_death